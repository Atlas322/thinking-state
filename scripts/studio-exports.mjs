// Writes src/lib/studio.ts — the @inai/thinking-state/studio entry: every
// single-file catalog component by its export name, so hosts (inai-sh) use
// the library instead of keeping copies. Module entries (src/company,
// src/motion, src/ui) are exported from the main entry already.
// Run: npm run studio:exports   (src/package.test.ts checks it is fresh)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const catalog = JSON.parse(fs.readFileSync(path.join(root, "src/catalog.json"), "utf8"));

export function studioEntries(cat, read) {
  const out = [];
  const missing = [];
  for (const e of cat) {
    if (e.module) continue;
    const src = read(`src/library/${e.slug}.tsx`);
    const re = new RegExp(String.raw`export\s+(?:function|const|class)\s+` + e.exportName + String.raw`\b`);
    if (re.test(src)) out.push({ slug: e.slug, name: e.exportName });
    else missing.push(`${e.slug}: ${e.exportName}`);
  }
  return { out, missing };
}

export function studioTs(entries) {
  const lines = entries.map((e) => `export { ${e.name} } from "../library/${e.slug}";`);
  return `/**
 * @inai/thinking-state/studio — every single-file catalog component, by the
 * catalog's export name (GENERATED by scripts/studio-exports.mjs; do not edit).
 * Hosts import from here instead of keeping copies:
 *   import { AgentInbox, DecisionCard } from "@inai/thinking-state/studio";
 * Each component carries its own styles and reads the --ts-* tokens.
 */
${lines.join("\n")}
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const { out, missing } = studioEntries(catalog, (p) => fs.readFileSync(path.join(root, p), "utf8"));
  if (missing.length) {
    console.error("catalog exportName not found as a named export:\n" + missing.join("\n"));
    process.exit(1);
  }
  fs.writeFileSync(path.join(root, "src/lib/studio.ts"), studioTs(out));
  console.log(`src/lib/studio.ts: ${out.length} components`);
}
